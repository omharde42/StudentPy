# Program: Swapping Two Variables

first_number = 10
second_number = 20

print("Before swapping:")
print("First number:", first_number)
print("Second number:", second_number)

first_number, second_number = second_number, first_number

print("\nAfter swapping:")
print("First number:", first_number)
print("Second number:", second_number)
